import { afterEach, describe, expect, it, vi } from "vitest";
import { Company, Contact, Country, Job, LeadAssignment, User, type CompanyDoc } from "@/models";
import { ingestCompanies, rebuildSnapshots } from "@/features/registry/sync";
import { getRegistryProvider } from "@/features/registry/providers";
import { clearTransientRegistry, transientRows } from "@/lib/db/transient-registry";
import { exportCompanies } from "@/features/companies/registrations";
import { sendLeadToMarketer, listMarketerLeads } from "@/features/marketer/service";
import { makeUser } from "./helpers";
import { normalizeBrregEnhet } from "@/features/registry/providers/brreg";
import { enqueueJob, processDueJobs, registerJobHandler } from "@/features/jobs/queue";
import type { CompanyRegistryProvider } from "@/features/registry/types";
import { reloadTransientCompany } from "@/features/registry/request-data";

afterEach(() => { clearTransientRegistry(); vi.restoreAllMocks(); vi.unstubAllEnvs(); vi.useRealTimers(); });
describe("registry storage boundaries", () => {
  it("pauses employment collection, including previously queued work, without deleting it", async () => {
    vi.stubEnv("JOB_COLLECTION_ENABLED", "false");
    const handler = vi.fn();
    registerJobHandler("opportunity-feed-sync", handler);
    const count = await Job.countDocuments();
    await enqueueJob("opportunity-feed-sync", "storage-pause-new", {});
    expect(await Job.countDocuments()).toBe(count);
    const queued = await Job.create({ type: "opportunity-feed-sync", key: "storage-pause-existing", payload: {}, runAt: new Date(0) });
    expect(await processDueJobs({ types: ["opportunity-feed-sync"], budgetMs: 100 })).toEqual({ processed: 0, failed: 0 });
    expect(handler).not.toHaveBeenCalled();
    expect((await Job.findById(queued._id).lean<{ status: string }>())?.status).toBe("QUEUED");
  });
  it("refetches a selected row after process memory is lost, using the existing source and date", async () => {
    const provider = getRegistryProvider("brreg")!;
    const row = normalizeBrregEnhet({ organisasjonsnummer: "999888776", navn: "Refetch fixture AS", registreringsdatoEnhetsregisteret: "2026-11-01" });
    await Country.updateOne({ code: "NO" }, { $set: { code: "NO", enabled: true, providerId: "brreg" } }, { upsert: true });
    const fetch = vi.spyOn(provider as Required<CompanyRegistryProvider>, "getRegistrations").mockResolvedValue({ companies: [row], complete: true, total: 1 });
    const result = await ingestCompanies(provider, "NO", [row]);
    const id = result.newIds[0]!;
    clearTransientRegistry();
    await reloadTransientCompany(id);
    expect(fetch).toHaveBeenCalledWith("2026-11-01", "2026-11-01", expect.anything());
    expect(await Company.findById(id).lean<CompanyDoc>()).toMatchObject({ companyName: "Refetch fixture AS" });
    expect(await Company.collection.findOne({ _id: new (await import("mongoose")).Types.ObjectId(id) })).toBeNull();
  });
  it("keeps source rows, raw data, filters, counts and exports in memory until marketer selection", async () => {
    const provider = getRegistryProvider("brreg")!;
    const row = normalizeBrregEnhet({ organisasjonsnummer: "999888777", navn: "Storage fixture AS", registreringsdatoEnhetsregisteret: "2026-11-01", organisasjonsform: { kode: "AS", beskrivelse: "Aksjeselskap" }, epostadresse: "hello@fixture.example", hjemmeside: "https://fixture.example" });
    vi.spyOn(provider as Required<CompanyRegistryProvider>, "getRegistrations").mockResolvedValue({ companies: [row], complete: true, total: 1 });
    const before = { companies: await Company.collection.countDocuments(), contacts: await Contact.collection.countDocuments(), jobs: await Job.countDocuments() };
    await ingestCompanies(provider, "NO", [row]);
    await ingestCompanies(provider, "NO", [row]);
    expect(await Company.collection.countDocuments()).toBe(before.companies);
    expect(await Contact.collection.countDocuments()).toBe(before.contacts);
    expect(await Job.countDocuments()).toBe(before.jobs);
    expect(transientRows(Company.collection.name)).toHaveLength(1);
    const company = await Company.findOne({ companyName: /Storage fixture/ }).lean<CompanyDoc>();
    expect(company?.registrationDay).toBe("2026-11-01");
    expect(await Company.countDocuments({ countryCode: "NO", registrationDay: "2026-11-01" })).toBe(1);
    expect(await Company.aggregate([{ $match: { countryCode: "NO" } }, { $group: { _id: "$registrationDay", n: { $sum: 1 } } }])).toContainEqual({ _id: "2026-11-01", n: 1 });
    await rebuildSnapshots("NO", "2026-11-01", "2026-11-01", { providerId: provider.id, isDemo: false, complete: true });
    const { actor } = await makeUser("OWNER");
    const exported = await exportCompanies(actor, { country: "NO", range: "custom", from: "2026-11-01", to: "2026-11-01" });
    expect(exported.csv).toContain("Storage fixture AS");
    expect(await Company.collection.countDocuments()).toBe(before.companies);
    const users = await User.countDocuments();
    await sendLeadToMarketer(actor, String(company!._id));
    expect(await Company.collection.countDocuments()).toBe(before.companies + 1);
    expect(await LeadAssignment.countDocuments({ companyId: company!._id })).toBe(1);
    expect(await Company.collection.findOne({ _id: company!._id })).not.toHaveProperty("sourceData");
    expect(await User.countDocuments()).toBe(users);
    clearTransientRegistry();
    const marketer = await makeUser("DIGITAL_MARKETER", { permissions: ["marketerLeads.view"] });
    expect((await listMarketerLeads({ ...marketer.actor, permissions: ["marketerLeads.view"] }, {})).items).toHaveLength(1);
  });
});
